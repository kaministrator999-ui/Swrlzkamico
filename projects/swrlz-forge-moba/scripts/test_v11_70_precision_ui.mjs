import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const {chromium}=require('/tmp/swyrl-browser-test/node_modules/playwright');
const browser=await chromium.launch({headless:true,executablePath:process.env.CHROME_BIN,
 args:['--no-sandbox','--enable-webgl','--enable-unsafe-swiftshader','--use-gl=angle','--use-angle=swiftshader']});
try{
 const page=await browser.newPage({viewport:{width:1100,height:800},deviceScaleFactor:1});
 const errors=[];
 page.on('pageerror',e=>errors.push(String(e)));
 await page.goto('http://127.0.0.1:8765/?project=model-atelier',{waitUntil:'domcontentloaded'});
 await page.waitForFunction(()=>window.__engineGizmoTest?.ready(),{timeout:45000});
 await page.evaluate(()=>window.__engineGizmoTest.pick());
 const state=()=>page.evaluate(()=>window.__engineGizmoTest.state());
 const bar=page.locator('#modelAtelierViewportModes');
 const strip=page.locator('#modelAtelierMeshQuickStrip');
 const slider=strip.locator('[data-mesh-precision] input[type=range]');
 await page.waitForFunction(()=>!!document.querySelector('#modelAtelierMeshQuickStrip [data-mesh-precision]'),{timeout:8000});
 assert.equal(await bar.locator('.atelier-top-render').count(),1,'render controls grouped');
 assert.equal(await bar.locator('.atelier-top-camera').count(),1,'camera views grouped');
 assert.equal(await bar.locator('.atelier-top-advanced').count(),1,'display/clip disclosure grouped');
 assert.equal(await bar.locator('#modelAtelierViewportMode').count(),1,'existing render mode preserved');
 assert.equal(await bar.locator('#modelAtelierViewportScope').count(),1,'existing display target preserved');
 assert.equal(await bar.locator('[data-at-view="front"]').count(),1,'camera direction preserved');
 assert.equal(await bar.locator('#modelAtelierViewportClipNear').count(),1,'clip controls preserved');
 assert.equal(await bar.locator('.atelier-top-advanced').evaluate(e=>e.open),false,'advanced defaults collapsed');
 await bar.locator('.atelier-top-advanced summary').click();
 assert.equal(await bar.locator('.atelier-top-advanced').evaluate(e=>e.open),true);
 assert.equal(await slider.inputValue(),'4','standard 1x sensitivity default');
 await bar.locator('.atelier-top-advanced summary').click();
 assert.equal(await bar.locator('.atelier-top-advanced').evaluate(e=>e.open),false);
 const handle=async()=>page.evaluate(()=>window.__engineGizmoTest.handle('x'));
 const move=async(px)=>{
  const p=await handle();assert.ok(p);
  const start=await state();
  const hit=await page.evaluate(p=>{const e=document.elementFromPoint(p.x,p.y);return e?.outerHTML?.slice(0,220)||'';},p);
  console.log('PRECISION_HANDLE_HIT',JSON.stringify({handle:p,start,hit}));
  await page.mouse.move(p.x,p.y);
  await page.mouse.down();
  await page.mouse.move(p.x+px,p.y-1,{steps:7});
  await page.waitForTimeout(100);
  const during=await state();
  console.log('PRECISION_DURING',JSON.stringify(during));
  assert.ok(during.dragging&&during.updates>0&&during.renders>0,'live previews drawn before pointer up');
  await page.mouse.up();
  await page.waitForTimeout(90);
  const final=await state();
  const dx=final.position[0]-start.position[0];
  console.log('MESHSENS_DRAG',JSON.stringify({px,dx,during,final}));
  assert.ok(Math.abs(dx)>0.0005,'drag changed selected mesh');
  return dx;
 };
 const baseline=await move(25);
 await slider.evaluate(el=>{el.value='0';el.dispatchEvent(new Event('input',{bubbles:true}))});
 assert.equal(await slider.inputValue(),'0');
 const stored=await page.evaluate(()=>JSON.parse(localStorage.getItem('swyrlz-atelier-transform-sensitivity-v1')));
 assert.equal(stored.move,0);
 const precise=await move(25);
 assert.ok(Math.abs(precise)<Math.abs(baseline)*.30,'fine slider makes drag significantly smaller');
 await strip.locator('[data-mode="rotate"]').click();
 assert.equal(await slider.inputValue(),'4','rotate has independent normal setting');
 await slider.evaluate(el=>{el.value='7';el.dispatchEvent(new Event('input',{bubbles:true}))});
 await strip.locator('[data-mode="move"]').click();
 assert.equal(await slider.inputValue(),'0','switching back remembers move setting');
 await page.setViewportSize({width:390,height:844});
 await page.waitForTimeout(150);
 assert.equal(await bar.locator('.atelier-top-camera button').count(),8,'all camera buttons preserved on narrow viewport');
 const clipped=await bar.evaluate(e=>e.getBoundingClientRect().width);
 assert.ok(clipped>0&&clipped<1000,'toolbar still renders on narrow viewport');
 assert.equal(errors.length,0,'no runtime errors: '+errors.join(' | '));
 console.log('SWRLZ_V1170_REAL_BROWSER_PRECISION_LAYOUT_PASS');
}finally{await browser.close();}
