import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const {chromium}=require('/tmp/swyrl-browser-test/node_modules/playwright');
const browser=await chromium.launch({headless:true,executablePath:process.env.CHROME_BIN,
 args:['--no-sandbox','--enable-webgl','--enable-unsafe-swiftshader','--use-gl=angle','--use-angle=swiftshader']});
try{
 const page=await browser.newPage({viewport:{width:1100,height:840}});
 const errors=[];page.on('pageerror',e=>errors.push(String(e)));
 await page.goto('http://127.0.0.1:8765/?project=model-atelier',{waitUntil:'domcontentloaded'});
 await page.waitForFunction(()=>window.__componentTest?.ready(),{timeout:45000});
 const initial=await page.evaluate(()=>window.__componentTest.scene());
 console.log('COMPONENT_BASELINE',JSON.stringify(initial));
 assert.equal(initial.parts,283,'Canonical character retained');
 assert.ok(initial.controls,'Component mode buttons exist');
 assert.ok(initial.meshes>=283,'Mesh data available');
 const name=await page.evaluate(()=>window.__componentTest.pick());
 console.log('COMPONENT_PART',name);
 await page.locator('[data-component-mode="vertex"]').click();
 await page.waitForFunction(()=>window.__componentTest.state().mode==='vertex');
 const info=await page.evaluate(()=>window.__componentTest.topology());
 console.log('COMPONENT_TOPOLOGY',JSON.stringify(info));
 assert.ok(info.vertices>10&&info.edges>10&&info.faces>10);
 assert.ok(info.overlay,'Vertex overlay should render');
 await page.evaluate(()=>window.__componentTest.choose(1));
 assert.equal((await page.evaluate(()=>window.__componentTest.state())).selected.length,1);
 const before=await page.evaluate(()=>window.__componentTest.affected());
 const modelBefore=await page.evaluate(()=>window.__componentTest.modelEdits());
 await page.locator('[data-component-nudge="1"]').click();
 const after=await page.evaluate(()=>window.__componentTest.affected());
 const modelAfter=await page.evaluate(()=>window.__componentTest.modelEdits());
 console.log('COMPONENT_VERTEX_EDIT',JSON.stringify({beforeSlots:before.ids.length,afterSlots:after.ids.length,firstBefore:before.positions[0],firstAfter:after.positions[0],modelBefore,modelAfter}));
 assert.ok(modelAfter.count>modelBefore.count,'Native indexed vertex edit persists');
 assert.notDeepEqual(after.positions,before.positions,'Moving component changes real geometry');
 assert.equal((await page.evaluate(()=>window.__componentTest.scene())).parts,283,'No geometry parts lost');
 await page.evaluate(()=>window.__componentTest.undo());
 await page.evaluate(()=>window.__componentTest.pick());
 await page.locator('[data-component-mode="vertex"]').click();
 await page.evaluate(()=>window.__componentTest.choose(1));
 assert.deepEqual((await page.evaluate(()=>window.__componentTest.affected())).positions,before.positions,
  'Undo restores exact original vertices');
 await page.evaluate(()=>window.__componentTest.redo());
 await page.evaluate(()=>window.__componentTest.pick());
 await page.locator('[data-component-mode="vertex"]').click();
 await page.evaluate(()=>window.__componentTest.choose(1));
 assert.deepEqual((await page.evaluate(()=>window.__componentTest.affected())).positions,after.positions,
  'Redo restores component edit');
 const save=await page.evaluate(()=>window.__componentTest.save());
 assert.ok(save.parts.some(p=>(p.sculptVertexEdits||[]).length));
 // Edge selections expand to two connected vertex families, faces to three.
 await page.locator('[data-component-mode="edge"]').click();
 await page.evaluate(()=>window.__componentTest.choose(0));
 const edge=await page.evaluate(()=>window.__componentTest.state());
 assert.ok(edge.expanded>=2&&edge.mode==='edge','Edge selected via same gizmo');
 await page.locator('[data-component-mode="face"]').click();
 await page.evaluate(()=>window.__componentTest.choose(0));
 const face=await page.evaluate(()=>window.__componentTest.state());
 assert.ok(face.expanded>=3&&face.mode==='face');
 await page.locator('[data-component-nudge="-1"]').click();
 assert.ok((await page.evaluate(()=>window.__componentTest.modelEdits())).count>modelAfter.count);
 // Exercise actual pointer capture on the component transform gizmo (before release).
 await page.locator('[data-component-mode="vertex"]').click();
 await page.evaluate(()=>window.__componentTest.choose(2));
 const h=await page.evaluate(()=>window.__componentTest.handle('x'));
 assert.ok(h&&Number.isFinite(h.x)&&Number.isFinite(h.y),'Component gizmo has a screen-space handle');
 const editsBeforeDrag=await page.evaluate(()=>window.__componentTest.modelEdits());
 await page.mouse.move(h.x,h.y);
 await page.mouse.down();
 await page.mouse.move(h.x+43,h.y,{steps:9});
 await page.waitForTimeout(100);
 const duringDrag=await page.evaluate(()=>window.__componentTest.dragState());
 console.log('COMPONENT_DRAG_DURING',JSON.stringify(duringDrag));
 assert.ok(duringDrag.active,'Live gizmo captures pointer before release');
 assert.ok(duringDrag.modified,'Actual component geometry moves while pointer is held');
 await page.mouse.up();
 await page.waitForTimeout(100);
 const editsAfterDrag=await page.evaluate(()=>window.__componentTest.modelEdits());
 assert.ok(editsAfterDrag.count>editsBeforeDrag.count,'Gizmo drag commits native vertex offsets');
 await page.evaluate(()=>window.__componentTest.choose(0));
 await page.locator('[data-component-multi]').click();
 await page.evaluate(()=>window.__componentTest.choose(2));
 assert.equal((await page.evaluate(()=>window.__componentTest.state())).selected.length,2);
 await page.evaluate(()=>window.__componentTest.choose(0));
 assert.equal((await page.evaluate(()=>window.__componentTest.state())).selected.length,1,
  'Tapped component toggles off in Multi');
 const pick=await page.evaluate(()=>window.__componentTest.region());
 console.log('COMPONENT_REGION',JSON.stringify(pick));
 assert.ok(pick.box>0&&pick.lasso>0,'Box and lasso selection operate on components');
 await page.setViewportSize({width:390,height:844});
 await page.waitForTimeout(100);
 const mobile=await page.evaluate(()=>window.__componentTest.mobile());
 console.log('COMPONENT_PHONE',JSON.stringify(mobile));
 assert.ok(mobile.modeButtons===4);
 assert.ok(mobile.minHeight>=37,'Touch controls remain finger-sized');
 assert.ok(mobile.visible,'Component controls remain visible on phone');
 await page.locator('[data-component-mode="mesh"]').click();
 assert.equal((await page.evaluate(()=>window.__componentTest.state())).mode,'mesh');
 assert.deepEqual(errors,[],'No runtime errors');
 console.log('SWRLZ_V1175_REAL_BROWSER_COMPONENT_EDIT_PASS');
}finally{await browser.close();}
