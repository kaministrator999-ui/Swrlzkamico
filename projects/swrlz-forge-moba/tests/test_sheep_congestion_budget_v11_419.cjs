const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const root=path.resolve(__dirname,'..');
const source=fs.readFileSync(path.join(root,'runtime/sheep_congestion_budget_v11_419.js'),'utf8');
assert(source.includes('SE419_SHEEP_CONGESTION_BUDGET_START'));
const sandbox={window:{}, stSession:{elapsed:1,controlledId:'owner',simulate:false,units:[]},
  renderer:{xr:{isPresenting:true}},se193XRGameActive:()=>true,se150Match:{active:false}};
vm.createContext(sandbox);vm.runInContext(source,sandbox);
const exec=x=>vm.runInContext(x,sandbox);
const sheep={kind:'sheep',id:'ai1',botIndex:0},other={kind:'sheep',id:'ai2',botIndex:1},owner={kind:'sheep',id:'owner'};
sandbox.stSession.units=[sheep,other,owner];
assert.equal(exec('se419TrafficActive(stSession.units[0])'),true);
assert.equal(exec('se419TrafficPermit(stSession.units[0])'),true);
assert.equal(exec('se419TrafficPermit(stSession.units[1])'),false,'second AI cannot path in same frame');
assert.equal(exec('se419Traffic.deferred'),1);
sandbox.stSession.elapsed=1.04;
assert.equal(exec('se419TrafficPermit(stSession.units[1])'),true,'budget resets next game tick');
assert.equal(exec('se419TrafficPermit(stSession.units[2])'),true,'player movement not gated');
sandbox.se150Match.active=true;
assert.equal(exec('se419TrafficPermit(stSession.units[0])'),true,'LAN never gated');
sandbox.se150Match.active=false;sandbox.renderer.xr.isPresenting=false;
assert.equal(exec('se419TrafficPermit(stSession.units[0])'),true,'non-VR never gated');
sandbox.renderer.xr.isPresenting=true;sandbox.stSession.simulate=true;
assert.equal(exec('se419TrafficPermit(stSession.units[0])'),true,'simulator not gated');
sandbox.stSession.simulate=false;sandbox.stSession={elapsed:0,controlledId:'owner',simulate:false,units:[sheep,other,owner]};
assert.equal(exec('se419TrafficPermit(stSession.units[0])'),true,'new session resets');
assert.equal(exec('se419Traffic.planned'),1);
const patch=fs.readFileSync(path.join(root,'patches/v11_419_sheep_congestion_budget.py'),'utf8');
for(const token of ['se419TrafficPermit(unit)','se419TryYield','se419Traffic.blockedStatic','se419YieldIndex','se419TrafficPause(unit,.72)','SE419_SHEEP_CONGESTION_BUDGET_START'])assert(patch.includes(token),token);
console.log('SHEEP_CONGESTION_419_PASS: one AI route per XR game tick, rotated yield, blocked-lane cooldown, player/nonXR/LAN bypass');
