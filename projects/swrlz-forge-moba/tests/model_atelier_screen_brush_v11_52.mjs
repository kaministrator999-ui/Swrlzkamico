import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import * as THREE from 'three';
const source=fs.readFileSync(new URL('../runtime/model_atelier_screen_brush_v11_52.js',import.meta.url),'utf8');
const c=vm.createContext({THREE,console});
vm.runInContext(source,c);
const radius=(mesh,camera,canvas,center,px)=>c.atelierBrushLocalRadiusFromPixels(mesh,camera,canvas,center,px);
const mesh=new THREE.Mesh(new THREE.SphereGeometry(.5,12,10),new THREE.MeshBasicMaterial());
const view=new THREE.PerspectiveCamera(60,800/600,.1,100);
view.position.set(0,0,4);view.lookAt(0,0,0);view.updateProjectionMatrix();view.updateMatrixWorld();
const surface={getBoundingClientRect:()=>({width:800,height:600})};
const center=new THREE.Vector3(0,0,0);
const a=radius(mesh,view,surface,center,20),b=radius(mesh,view,surface,center,40);
assert(a>0&&b>a&&Math.abs(b/a-2)<.015,'screen pixel radius should scale linearly');
view.position.set(0,0,2);view.lookAt(0,0,0);view.updateMatrixWorld();
const closer=radius(mesh,view,surface,center,40);
assert(closer<b*.55&&closer>b*.45,'perspective zoom must change local radius');
const ortho=new THREE.OrthographicCamera(-2,2,1.5,-1.5,.1,30);
ortho.position.set(0,0,5);ortho.lookAt(0,0,0);ortho.updateMatrixWorld();
const orthoA=radius(mesh,ortho,surface,center,20);
ortho.position.set(0,0,10);ortho.updateMatrixWorld();
assert(Math.abs(orthoA-radius(mesh,ortho,surface,center,20))<1e-7,
 'orthographic viewport radius must not depend on camera distance');
assert.equal(radius(mesh,view,surface,center,201),null,'reject excessive screen radius');
assert.equal(radius(mesh,view,surface,center,-1),null,'reject negative radius');
const headScale=new THREE.Mesh(new THREE.SphereGeometry(.5,8,8),new THREE.MeshBasicMaterial());
headScale.scale.set(.285,.346,.26);
const actualHeadRadius=radius(headScale,view,surface,center,40);
assert(actualHeadRadius>.03&&actualHeadRadius<=2.5,
 'native original 283-part head with realistic nonuniform XYZ scale must remain editable');
const nonuniform=new THREE.Mesh(new THREE.SphereGeometry(.5,8,8),new THREE.MeshBasicMaterial());
nonuniform.scale.set(4,1,1);
assert.equal(radius(nonuniform,view,surface,center,40),null,'reject misleading anisotropic local sphere');
const short={getBoundingClientRect:()=>({width:4,height:600})};
assert.equal(radius(mesh,view,short,center,40),null,'reject unmeasurable viewport');
assert.equal(radius(mesh,view,surface,new THREE.Vector3(0,0,100),40),null,'reject center outside clip');
assert.equal(mesh.geometry.attributes.position.count>0,true);
console.log('V1152_CAMERA_PIXEL_TO_LOCAL_BRUSH_RADIUS_PERSPECTIVE_ORTHO_SCALE_INVALID_PASS');
