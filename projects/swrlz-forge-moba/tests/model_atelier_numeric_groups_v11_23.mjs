import assert from 'node:assert/strict';
import vm from 'node:vm';import fs from 'node:fs';import * as THREE from 'three';
const source=fs.readFileSync(new URL('../runtime/model_atelier_numeric_gizmos_v11_23.js',import.meta.url),'utf8');
const ctx=vm.createContext({THREE,console});vm.runInContext(source,ctx);
const run=(mesh,ids,mode,space,vector,snap=0)=>ctx.atelierGroupEdit(mesh,ids,mode,space,vector,snap);
const g=new THREE.PlaneGeometry(1,1,2,2);
const mesh=new THREE.Mesh(g,new THREE.MeshBasicMaterial());
const ids=[0,1,3,4];
const moved=run(mesh,ids,'translate','object',[0,0,.1]);
assert(moved&&moved.moves.length===4);
assert(moved.moves.every(x=>Math.abs(x[2]-.1)<1e-7));
assert.equal(run(mesh,ids,'translate','object',[.8,0,0]),null);
assert.equal(run(mesh,ids,'scale','object',[0,1,1]),null);
const scale=run(mesh,ids,'scale','object',[2,1,1]);
assert(scale&&scale.moves.some(x=>Math.abs(x[0])>.1));
const rotate=run(mesh,ids,'rotate','object',[0,0,90]);
assert(rotate&&rotate.moves.some(x=>Math.abs(x[1])>.1));
mesh.rotation.y=Math.PI/2;
const world=run(mesh,[4],'translate','world',[0,0,.1]);
assert(world&&world.moves[0][0]<-.09,'World +Z maps into object -X after a +90° Y rotation');
const surface=run(mesh,[4],'translate','surface',[0,0,.08],.01);
assert(surface&&Math.abs(surface.moves[0][2]-.08)<.0001);
const invalid=run(mesh,[3,3],'scale','object',[1,1,2]);
assert.equal(invalid,null);
assert.equal(JSON.parse(JSON.stringify(moved)).moves.length,4);
console.log('V1123_NUMERIC_VERTEX_GROUP_TRANSLATE_ROTATE_SCALE_SPACES_SAVE_PASS');
