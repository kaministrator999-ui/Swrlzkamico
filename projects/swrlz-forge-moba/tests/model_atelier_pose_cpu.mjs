import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const code=readFileSync(new URL('../runtime/model_atelier_pose_frames_v11_11.js',import.meta.url),'utf8');
const ctx={MODEL_ATELIER_LIMIT:1200,model:()=>({parts:[]})};
vm.createContext(ctx);
vm.runInContext(code,ctx);
const leg={kind:'loft',surfaceStyle:'anatomy-smooth',path:[[.2,2.07,0],[.2,1.78,0],[.2,1.39,0],[.2,1.12,0],[.2,.88,0],[.2,.6,0]]};
const original=JSON.parse(JSON.stringify(leg.path));
vm.runInContext("atelierBendNativeLeg",ctx)(leg,.30,.04);
assert.equal(leg.path[0][2],original[0][2],'Hip must remain anchored');
assert.equal(leg.path[5][2],original[5][2],'Ankle must remain anchored');
assert(leg.path[3][2]>.29,'Knee geometry did not bend forward');
assert(leg.path[2][2]>.1,'Thigh/surface transition did not interpolate');
assert(leg.path[3][0]>.2,'Knee lateral offset not applied');
const frame={name:'My idle',poses:[{id:'leg',position:[0,0,0],rotation:[0,0,0],scale:[1,1,1],path:leg.path}]};
const valid=vm.runInContext("atelierValidPoseFrame",ctx);
assert(valid(frame));
assert(!valid({...frame,poses:[...frame.poses,frame.poses[0]]}),'Duplicate pose IDs accepted');
assert(!valid({...frame,poses:[{...frame.poses[0],position:[Infinity,0,0]}]}));
assert(!valid({...frame,poses:[{...frame.poses[0],path:[[0,0,0]]}]}));
assert(!valid({...frame,camera:{yaw:Infinity,pitch:0,distance:9}}));
console.log('MODEL_ATELIER_NATIVE_KNEE_POSE_CPU_PASS');
